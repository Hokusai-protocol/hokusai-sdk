import { describe, expect, it } from 'vitest';
import {
  detectBodyDisclosure,
  hasAiCodemodSubject,
  isUpstreamImportTitle,
} from './disclosures.js';

describe('explicit disclosures', () => {
  it('matches affirmative statements only', () => {
    expect(
      detectBodyDisclosure('Summary:\nThis is an AI generated diff.'),
    ).toBe('explicit_ai_generated_change');
    expect(detectBodyDisclosure('- Agent-authored; tests only.')).toBe(
      'explicit_agent_authored',
    );
    expect(detectBodyDisclosure('Generated by Mintlify Agent.')).toBe(
      'explicit_named_agent_creator',
    );
    expect(
      detectBodyDisclosure(
        'Was generative AI tooling used to co-author this PR?\n- [x] Yes\n- Cursor',
      ),
    ).toBe('checked_airflow_ai_disclosure');
    for (const body of [
      null,
      'Was generative AI tooling used to co-author this PR?\n- [ ] Yes\n- Cursor',
      '```\nThis is an AI generated diff.\n```',
      '<!-- Generated by Mintlify Agent. -->',
      'This is not an AI generated diff.',
      'Document the AI generated diff feature.',
    ])
      expect(detectBodyDisclosure(body)).toBeNull();
  });
  it('reads the AI Codemod tag from a commit subject, not from prose', () => {
    expect(
      hasAiCodemodSubject(['[AI Codemod][Perf] Skip a scan\n\nBody']),
    ).toBe(true);
    expect(
      hasAiCodemodSubject(['Fix\n\nReverts the [AI Codemod] change', '']),
    ).toBe(false);
  });
  it('recognizes upstream import titles', () => {
    for (const title of [
      '`rust-analyzer` subtree update',
      '[main] Source code updates from dotnet/dotnet',
      'Docs: sync upstream clickhouse-operator docs updates',
    ])
      expect(isUpstreamImportTitle(title)).toBe(true);
    expect(isUpstreamImportTitle('Fix subtree walk in the resolver')).toBe(
      false,
    );
    expect(isUpstreamImportTitle(null)).toBe(false);
  });
});
