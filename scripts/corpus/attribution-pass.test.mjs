import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  classifyAttribution,
  chooseSample,
  summarizeAttribution,
  exploratoryDisclosure,
} from './attribution-pass.mjs';

test('exploratory disclosures require affirmative statements and ignore quoted templates', () => {
  assert.equal(
    exploratoryDisclosure(
      'Summary:\nThis is an AI generated diff. The diff is human reviewed.',
    ),
    'explicit_ai_generated_change',
  );
  assert.equal(
    exploratoryDisclosure('- Agent-authored; only automated tests ran.'),
    'explicit_agent_authored',
  );
  assert.equal(
    exploratoryDisclosure('Generated by Mintlify Agent.'),
    'explicit_named_agent_creator',
  );
  assert.equal(
    exploratoryDisclosure(
      'This PR was created by the Inkeep Content Writer agent, which is maintained by the docs team.',
    ),
    'explicit_named_agent_creator',
  );
  assert.equal(
    exploratoryDisclosure(
      'Was generative AI tooling used to co-author this PR?\n- [x] Yes (please specify the tool below)\n- Cursor',
    ),
    'checked_airflow_ai_disclosure',
  );
  assert.equal(
    exploratoryDisclosure(
      'Was generative AI tooling used to co-author this PR?\n- [ ] Yes\n- Cursor',
    ),
    null,
  );
  assert.equal(
    exploratoryDisclosure(
      '```\nThis is an AI generated diff.\n```\n<!-- Generated by Mintlify Agent. -->',
    ),
    null,
  );
  assert.equal(
    exploratoryDisclosure(
      'This is not an AI generated diff.\nDocument the AI generated diff feature.\n> Agent-authored; example',
    ),
    null,
  );
});

const protocol = {
  label_semantics: { 'ai-assisted': 'agent' },
  ambiguous_tool_labels: ['copilot'],
  owner_mappings: {},
  seed: 'fixed',
  sample_per_repo_stratum: {
    baseline_positive: 2,
    added_positive: 2,
    unmarked: 2,
    bot_without_agent_evidence: 2,
  },
};
const feature = {
  repo: 'test/repo',
  as_of: '2026-01-01T00:00:00Z',
  features: { 'feature.agent.marker_present': false },
};
const record = { author_login: 'alice', author_type: 'User', head_sha: 'abcd' };
const evidence = {
  body: '',
  body_edits: [],
  label_events: [],
  head_ref: 'feature/x',
};

test('generic automation is separate while independently observed agent evidence survives', () => {
  const bot = {
    ...record,
    author_login: 'dependabot[bot]',
    author_type: 'Bot',
  };
  const unmarked = classifyAttribution(feature, bot, evidence, protocol);
  assert.equal(unmarked.positive, false);
  assert.equal(unmarked.genericBot, true);
  assert.equal(unmarked.dependencyBot, true);
  assert.equal(unmarked.stratum, 'bot_without_agent_evidence');
  const assisted = classifyAttribution(
    { ...feature, features: { 'feature.agent.marker_present': true } },
    bot,
    evidence,
    protocol,
  );
  assert.equal(assisted.positive, true);
  assert.equal(assisted.stratum, 'baseline_positive');
});

test('historical label state excludes topic labels and labels added after merge', () => {
  const e = {
    ...evidence,
    label_events: [
      { at: '2025-12-31T00:00:00Z', action: 'added', label: 'copilot' },
      { at: '2026-01-02T00:00:00Z', action: 'added', label: 'ai-assisted' },
    ],
  };
  assert.equal(
    classifyAttribution(feature, record, e, protocol).positive,
    false,
  );
  e.label_events[1].at = '2025-12-31T00:00:00Z';
  assert.equal(
    classifyAttribution(feature, record, e, protocol).signals
      .explicit_agent_label,
    true,
  );
  e.label_events.push({
    at: '2025-12-31T01:00:00Z',
    action: 'removed',
    label: 'ai-assisted',
  });
  assert.equal(
    classifyAttribution(feature, record, e, protocol).positive,
    false,
  );
});

test('metadata separates harness claims from head-bound executed models and rejects stale heads', () => {
  const e = {
    ...evidence,
    body: '<!-- wavemill-meta\nexecutedRoute: coder\nharness: codex\nmodel: gpt-5\n-->',
  };
  const unbound = classifyAttribution(feature, record, e, protocol);
  assert.equal(unbound.positive, true);
  assert.equal(unbound.executedModel, null);
  const bound = classifyAttribution(
    feature,
    record,
    { ...e, body: e.body.replace('-->', 'headSha: abcd\n-->') },
    protocol,
  );
  assert.equal(bound.executedModel, 'gpt-5');
  const stale = classifyAttribution(
    feature,
    record,
    { ...e, body: e.body.replace('-->', 'headSha: dead\n-->') },
    protocol,
  );
  assert.equal(stale.positive, false);
  assert.equal(stale.metadataHeadMismatch, true);
});

test('later body changes cannot add historical attribution; missing evidence stays unavailable', () => {
  const e = {
    ...evidence,
    body: '<!-- wavemill-meta\nharness: codex\n-->',
    body_edits: [
      {
        at: '2026-01-02T00:00:00Z',
        body: '<!-- wavemill-meta\nharness: codex\n-->',
      },
    ],
  };
  const r = classifyAttribution(feature, record, e, protocol);
  assert.equal(r.positive, false);
  assert.equal(r.bodyUnavailable, true);
  assert.equal(
    classifyAttribution(feature, record, null, protocol).labelsUnavailable,
    true,
  );
});

test('union is per PR, incremental signal counts overlap, and samples are order independent', () => {
  const baseline = classifyAttribution(
    { ...feature, features: { 'feature.agent.marker_present': true } },
    record,
    evidence,
    protocol,
  );
  const added = classifyAttribution(
    feature,
    record,
    {
      ...evidence,
      body: '<!-- wavemill-meta\nharness: codex\n-->',
      label_events: [
        { at: '2025-12-31', action: 'added', label: 'ai-assisted' },
      ],
    },
    protocol,
  );
  const rows = [baseline, added].map((r, i) => ({
    repo: 'test/repo',
    pr_number: i + 1,
    ...r,
  }));
  const s = summarizeAttribution(rows);
  assert.equal(s.full_union, 2);
  assert.equal(s.added_unique, 1);
  assert.equal(s.additional_by_signal_overlapping.explicit_agent_label, 1);
  assert.equal(s.additional_by_signal_overlapping.declared_harness_metadata, 1);
  assert.deepEqual(
    chooseSample(rows, protocol),
    chooseSample([...rows].reverse(), protocol),
  );
  assert.equal(chooseSample(rows, protocol)[0].stratum_population, 1);
});
