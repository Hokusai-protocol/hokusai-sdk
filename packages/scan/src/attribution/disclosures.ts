/**
 * Affirmative AI-authorship disclosures that name no recognized tool signature
 * (HOK-2822 protocol 1.2.0).
 *
 * These complement `detectAgentMarkers`, whose output feeds versioned feature
 * rows and is therefore left unchanged. Matching favours precision: a statement
 * must open its line, and fenced code and HTML template comments are ignored, so
 * an unchecked template or a PR that discusses AI-generated code does not match.
 */

export type BodyDisclosureRule =
  | 'explicit_ai_generated_change'
  | 'explicit_agent_authored'
  | 'explicit_named_agent_creator'
  | 'checked_airflow_ai_disclosure';

export function detectBodyDisclosure(
  body: string | null | undefined,
): BodyDisclosureRule | null {
  if (!body) return null;
  const text = body
    .replace(/```[\s\S]*?```/g, '')
    .replace(/<!--[\s\S]*?-->/g, '');
  if (
    /^\s*(?:This (?:is an? |(?:PR|pull request|change|diff|patch) (?:is|was) (?:an? )?))AI[- ](?:generated|authored|assisted)\b/im.test(
      text,
    )
  )
    return 'explicit_ai_generated_change';
  if (/^\s*(?:[-*]\s*)?Agent[- ]authored\b/im.test(text))
    return 'explicit_agent_authored';
  if (
    /^\s*Generated by Mintlify Agent[.!]?\s*$/im.test(text) ||
    /^\s*This PR was created by the Inkeep Content Writer agent\b/im.test(text)
  )
    return 'explicit_named_agent_creator';
  const question = text.match(
    /Was generative AI tooling used to co-author this PR\?([\s\S]{0,1000})/i,
  )?.[1];
  if (
    question &&
    /^\s*-\s*\[x\]\s*Yes\b/im.test(question) &&
    /\b(?:Cursor|Claude|Copilot|Codex|Aider|OpenHands|Gemini)\b/i.test(question)
  )
    return 'checked_airflow_ai_disclosure';
  return null;
}

/** A commit whose subject opens with the `[AI Codemod]` tag. */
export function hasAiCodemodSubject(messages: readonly string[]): boolean {
  return messages.some((message) => /^\[AI Codemod\]/i.test(message));
}

/**
 * A PR that transports work authored elsewhere (subtree updates, codeflow and
 * upstream syncs). Markers in such a PR describe the upstream work: they are
 * agent evidence with an inherited scope, not evidence about how this PR was made.
 */
export function isUpstreamImportTitle(
  title: string | null | undefined,
): boolean {
  if (!title) return false;
  return (
    /\bsubtree (?:update|sync)\b/i.test(title) ||
    /^\[[^\]]+\] Source code updates from \S+/i.test(title) ||
    /\bsync upstream\b/i.test(title)
  );
}
