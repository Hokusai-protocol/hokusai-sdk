/**
 * Regenerates packages/core/src/fixtures/task-cost/wavemill-golden.ts by
 * running Wavemill's real `buildExecutionEconomics` over each SDK task-cost
 * fixture that corresponds to a Wavemill session.
 *
 * Run from a Wavemill checkout (it imports Wavemill's TypeScript directly):
 *
 *   cd "$WAVEMILL" && npx tsx "$SDK/scripts/generate-wavemill-task-cost-golden.mjs" "$SDK"
 *
 * Not part of the SDK build or test run; the committed golden is the artifact.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const sdkRoot = path.resolve(process.argv[2] ?? '');
const wavemillRoot = process.cwd();
const coreSrc = path.join(sdkRoot, 'packages/core/src');

const { buildExecutionEconomics } = await import(
  path.join(wavemillRoot, 'shared/lib/execution-economics.ts')
);
const { taskCostFixtures } = await import(path.join(coreSrc, 'fixtures/task-cost/index.ts'));
const { MODEL_PRICING } = await import(path.join(coreSrc, 'pricing.ts'));

/** Fixtures whose events map one-to-one onto a single Wavemill session. */
const PARITY_FIXTURES = [
  'claude-code-simple',
  'claude-code-model-switch',
  'claude-code-cache-tiers',
  'codex-simple',
  'codex-unknown-pricing',
  'codex-provider-override',
  'partial-usage',
  'wavemill-parity',
];

const USAGE_KEYS = [
  ['inputTokens', 'input_tokens'],
  ['outputTokens', 'output_tokens'],
  ['cacheReadTokens', 'cache_read_tokens'],
  ['cacheWriteTokens', 'cache_write_tokens'],
  ['reasoningTokens', 'reasoning_tokens'],
];

/** Wavemill's price shape, derived from the SDK table so both sides price identically. */
const pricingTable = Object.fromEntries(
  Object.entries(MODEL_PRICING).map(
    ([model, price]) => [
      model,
      {
        inputCostPerMTok: price.inputPerMTokUsd,
        outputCostPerMTok: price.outputPerMTokUsd,
        cacheWriteCostPerMTok: price.inputPerMTokUsd * 1.25,
        cacheReadCostPerMTok: price.inputPerMTokUsd * 0.1,
      },
    ],
  ),
);

function addObserved(a, b) {
  if (a === null) return b;
  if (b === null) return a;
  return a + b;
}

const goldens = {};
for (const name of PARITY_FIXTURES) {
  const fixture = taskCostFixtures.find((candidate) => candidate.name === name);
  if (!fixture) throw new Error(`unknown fixture ${name}`);
  const [expected] = fixture.expectedSummaries;

  const turns = fixture.events.map((event) => ({
    turnId: event.turn_id,
    parentId: null,
    isSubagent: null,
    model: event.observed_model,
    timestamp: event.observed_at,
    usage: Object.fromEntries(USAGE_KEYS.map(([camel, snake]) => [camel, event.usage[snake]])),
    usageAvailable: event.usage_coverage !== 'unavailable',
    actualCostUsd: null,
  }));
  const usage = Object.fromEntries(
    USAGE_KEYS.map(([camel]) => [
      camel,
      turns.reduce((sum, turn) => addObserved(sum, turn.usage[camel]), null),
    ]),
  );
  const actuals = fixture.events
    .map((event) => event.actual_cost_usd)
    .filter((value) => value !== null);
  const actualCostUsd =
    actuals.length === 0
      ? null
      : Math.round(actuals.reduce((sum, value) => sum + value, 0) * 1e9) / 1e9;

  const [block] = buildExecutionEconomics({
    scanResults: [
      {
        models: {},
        sessionCount: 1,
        turnCount: turns.length,
        externalSessions: [
          {
            sessionId: 'session-0001',
            harness: fixture.ledger.harness,
            harnessVersion: fixture.ledger.harness_version ?? null,
            triggerSource: null,
            triggerProvenance: null,
            startedAt: null,
            endedAt: null,
            turnCount: turns.length,
            turns,
            usage,
            actualCostUsd,
            diagnostics: [],
          },
        ],
      },
    ],
    pricingTable,
    pricingRevision: expected.pricing_revision ?? null,
    now: () => new Date(expected.collected_at),
  });
  const [session] = block.sessions;
  goldens[name] = {
    providerContractVersion: block.providerContractVersion,
    harness: block.harness,
    usage: session.usage,
    actualCostUsd: session.actualCostUsd,
    estimatedCostUsd: session.estimatedCostUsd,
    costSource: session.costSource,
    pricingRevision: session.pricingRevision,
    pricingTimestamp: session.pricingTimestamp,
    coverage: session.coverage,
    turnCount: session.turnCount,
    modelSegments: session.modelSegments,
  };
}

const wavemillCommit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
  cwd: wavemillRoot,
  encoding: 'utf8',
}).trim();

const source = `/**
 * Wavemill parity goldens. GENERATED by scripts/generate-wavemill-task-cost-golden.mjs
 * from Wavemill @ ${wavemillCommit} (shared/lib/execution-economics.ts,
 * EXECUTION_ECONOMICS_SCHEMA_VERSION 1.0.0) over the matching task-cost
 * fixtures. Do not edit by hand; regenerate and review the diff.
 *
 * Each entry is the cost-relevant subset of the \`EvalExecutionEconomics\`
 * session Wavemill emits for that fixture, keyed by fixture name. Keys keep
 * Wavemill's camelCase on purpose: this is Wavemill's output, verbatim.
 *
 * @module fixtures/task-cost/wavemill-golden
 */

export interface WavemillGoldenSession {
  providerContractVersion: string;
  harness: 'claude-code' | 'codex';
  usage: {
    inputTokens: number | null;
    outputTokens: number | null;
    cacheReadTokens: number | null;
    cacheWriteTokens: number | null;
    reasoningTokens: number | null;
  };
  actualCostUsd: number | null;
  estimatedCostUsd: number | null;
  costSource: 'provider_reported' | 'local_estimate' | 'none';
  pricingRevision: string | null;
  pricingTimestamp: string | null;
  coverage: 'complete' | 'partial' | 'unavailable' | 'known_zero';
  turnCount: number;
  modelSegments: Array<{ model: string; turnCount: number }>;
}

export const wavemillGoldens: Readonly<Record<string, WavemillGoldenSession>> = ${JSON.stringify(goldens, null, 2)};
`;

writeFileSync(path.join(coreSrc, 'fixtures/task-cost/wavemill-golden.ts'), source);
console.log(`wrote golden for ${PARITY_FIXTURES.length} fixtures from Wavemill @ ${wavemillCommit}`);
